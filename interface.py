"""Native Tk interface; tracking stays in maxtrack.py."""
import tkinter as tk
from tkinter import ttk
from settings_store import CAMERA_FPS_OPTIONS

def build_interface(app):
    root=app.root
    root.geometry('1100x760');root.minsize(1000,700)
    style=ttk.Style(root)
    style.configure('.',background='#101722',foreground='#e8eef7',font=('Segoe UI',10))
    style.configure('Card.TFrame',background='#192433')
    style.configure('Card.TLabel',background='#192433')
    style.configure('Muted.TLabel',foreground='#93a5ba')
    style.configure('Title.TLabel',font=('Segoe UI',24,'bold'))
    style.configure('Accent.TButton',background='#29b6a6',foreground='#071c20',font=('Segoe UI',11,'bold'),padding=(16,12))
    style.map('Accent.TButton',background=[('active','#52d2c3')])
    style.configure('TNotebook',background='#101722',borderwidth=0)
    style.configure('TNotebook.Tab',padding=(18,10),background='#243247')
    style.map('TNotebook.Tab',background=[('selected','#35516d')])
    root.configure(background='#101722')
    page=ttk.Frame(root,padding=22);page.pack(fill='both',expand=True)
    header=ttk.Frame(page);header.pack(fill='x',pady=(0,18))
    ttk.Label(header,text='MaxTrack',style='Title.TLabel').pack(side='left')
    ttk.Label(header,text='PRO  /  0.9.21',style='Muted.TLabel').pack(side='left',padx=14)
    if app.tray is not None:
        ttk.Button(header, text='Minimizar para a bandeja', command=app.minimize_to_tray).pack(side='right')
    app.fps_info=tk.StringVar(value='CAPTURA  — FPS')
    ttk.Label(header,textvariable=app.fps_info,font=('Segoe UI',12,'bold'),foreground='#52d2c3').pack(side='right',padx=(0, 12))
    body=ttk.Frame(page);body.pack(fill='both',expand=True)
    body.columnconfigure(0,weight=1);body.columnconfigure(1,weight=1)
    body.rowconfigure(0,weight=1)
    left=ttk.Frame(body);left.grid(row=0,column=0,sticky='nsew',padx=(0,20))
    right=ttk.Frame(body);right.grid(row=0,column=1,sticky='nsew')
    card=ttk.Frame(left,style='Card.TFrame',padding=12);card.pack(fill='x')
    ttk.Label(card,text='SUA CÂMERA',style='Card.TLabel',font=('Segoe UI',10,'bold')).pack(anchor='w',pady=(0,10))
    preview_holder=tk.Frame(card,bg='#090f17',width=480,height=360)
    preview_holder.pack(fill='x');preview_holder.pack_propagate(False)
    app.preview=tk.Label(preview_holder,text='Preparando webcam…',bg='#090f17',fg='#93a5ba')
    app.preview.pack(fill='both',expand=True)
    app.preview_image=None
    ttk.Label(left,textvariable=app.mode,font=('Segoe UI',11,'bold'),foreground='#52d2c3').pack(anchor='w',pady=(14,4))
    ttk.Label(left,textvariable=app.info,wraplength=470).pack(anchor='w')
    controls=ttk.Frame(left);controls.pack(fill='x',pady=14)
    ttk.Button(controls,text='Centralizar  ·  F10',style='Accent.TButton',command=app.recenter).pack(side='left',fill='x',expand=True,padx=(0,8))
    ttk.Button(controls,text='Pausar / ativar  ·  F9',command=app.toggle).pack(side='left',fill='x',expand=True)
    ttk.Label(left,text='Olhe para frente e centralize antes de dirigir.\nTodo o processamento acontece neste computador.',style='Muted.TLabel').pack(anchor='w')
    top=ttk.Frame(right);top.pack(fill='x',pady=(0,12))
    ttk.Label(top,text='Perfil de direção',font=('Segoe UI',12,'bold')).pack(side='left')
    profiles=ttk.Combobox(top,textvariable=app.profile_name,values=['ETS2','ATS'],state='readonly',width=10)
    profiles.pack(side='right');profiles.bind('<<ComboboxSelected>>',app.switch_profile)
    notebook=ttk.Notebook(right);notebook.pack(fill='both',expand=True)
    adjust=ttk.Frame(notebook,padding=16);advanced=ttk.Frame(notebook,padding=16);diagnostic=ttk.Frame(notebook,padding=16)
    notebook.add(adjust,text='Movimento');notebook.add(advanced,text='Câmera e saída');notebook.add(diagnostic,text='Diagnóstico')
    ttk.Checkbutton(adjust,text='Resposta rápida nas viradas',variable=app.vars['responsive'],command=app.sync).pack(anchor='w')
    ttk.Label(adjust,text='Reduz o atraso durante o movimento e mantém\na estabilidade quando você para.',style='Muted.TLabel').pack(anchor='w',pady=(4,12))
    ttk.Checkbutton(adjust,text='Modo Cabine imersiva',variable=app.vars['cabin_mode'],command=app.sync).pack(anchor='w')
    ttk.Label(adjust,text='Aproxime a cabeça e vire para qualquer lado para olhar\nmais longe pela janela. Use a ponte direta SCS no ETS2.',style='Muted.TLabel').pack(anchor='w',pady=(4,8))
    for label,key,lo,hi in [('Horizontal','sensitivity_x',.3,5),('Vertical','sensitivity_y',.3,5),('Suavização','smoothing',0,.9),('Anti-tremor · graus','anti_tremor',0,2),('Zona morta central · graus','deadzone',0,6)]:
        row=ttk.Frame(adjust);row.pack(fill='x',pady=5)
        ttk.Label(row,text=label).pack(side='left')
        value=ttk.Entry(row,textvariable=app.vars[key],width=8,justify='center');value.pack(side='right')
        value.bind('<Return>',lambda _e:app.sync());value.bind('<FocusOut>',lambda _e:app.sync())
        ttk.Scale(adjust,variable=app.vars[key],from_=lo,to=hi,command=lambda _v:app.sync()).pack(fill='x')
    ttk.Button(adjust,text='Aplicar ajuste de resposta rápida',command=app.apply_responsive_preset).pack(fill='x',pady=(16,4))
    ttk.Label(adjust,text='Configurações salvas automaticamente por perfil.',style='Muted.TLabel').pack(anchor='w',pady=5)
    ttk.Label(advanced,text='Webcam',font=('Segoe UI',12,'bold')).pack(anchor='w')
    app.camera_combo=ttk.Combobox(advanced,textvariable=app.camera,values=[app.camera.get()],width=10,state='readonly')
    app.camera_combo.pack(fill='x',pady=8);app.camera_combo.bind('<<ComboboxSelected>>',lambda _e:app.restart())
    ttk.Button(advanced,text='Buscar webcams',command=app.detect_cameras).pack(fill='x',pady=3)
    ttk.Button(advanced,text='Reabrir webcam',command=app.restart).pack(fill='x',pady=3)
    fps_row = ttk.Frame(advanced)
    fps_row.pack(fill='x', pady=(10, 4))
    ttk.Label(fps_row, text='Limite da webcam (FPS)').pack(side='left')
    fps_combo = ttk.Combobox(fps_row, textvariable=app.vars['camera_fps'],
                             values=CAMERA_FPS_OPTIONS, state='readonly', width=7)
    fps_combo.pack(side='right')
    fps_combo.bind('<<ComboboxSelected>>', lambda _event: app.sync())
    for label,key in [('Inverter horizontal','invert_x'),('Inverter vertical','invert_y'),('Movimento vertical','vertical'),('Melhorar pouca luz · usa mais processamento','lowlight')]:
        ttk.Checkbutton(advanced,text=label,variable=app.vars[key],command=app.sync).pack(anchor='w',pady=8)
    ttk.Separator(advanced).pack(fill='x',pady=12)
    ttk.Checkbutton(advanced,text='Usar ponte direta SCS · experimental',variable=app.vars['direct_bridge'],command=app.sync).pack(anchor='w')
    ttk.Label(advanced,text='Requer integração configurada no jogo.\nDesmarcado: saída de compatibilidade OpenTrack.',style='Muted.TLabel',wraplength=390).pack(anchor='w',pady=8)
    ttk.Label(diagnostic,text='Estado do rastreamento',font=('Segoe UI',12,'bold')).pack(anchor='w',pady=(0,14))
    ttk.Label(diagnostic,textvariable=app.pose_info,wraplength=380).pack(anchor='w',pady=10)
    ttk.Label(diagnostic,textvariable=app.udp_info,wraplength=380).pack(anchor='w',pady=10)
    ttk.Label(diagnostic,text='O FPS mostrado é da captura e processamento,\nnão o FPS do jogo. Queda aqui pode afetar a fluidez.',style='Muted.TLabel').pack(anchor='w',pady=14)
    ttk.Button(diagnostic,text='Testar movimento por 3 segundos',command=app.test_udp).pack(fill='x',pady=8)
    ttk.Button(diagnostic,text='Restaurar ajustes originais do perfil',command=app.apply_preset).pack(fill='x',pady=8)
    app.log('Iniciando MaxTrack 0.9.21')
